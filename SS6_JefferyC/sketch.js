// Array 1: Holds active node objects (positions, velocities, colors, and base radii)
let nodes = [];

// Array 2: Holds active expanding wave/ripple rings generated by clicks
let ripples = [];

// Array 3: Preset color palette for dynamic lighting states
const nodePalette = [
  [0, 240, 255],   // Cyan
  [255, 0, 150],   // Magenta
  [255, 200, 0],   // Amber
  [120, 255, 0]    // Electric Lime
];

function setup() {
  createCanvas(800, 600);
  colorMode(HSB, 360, 100, 100, 1);
  
  // Seed the array with an initial structural grid of nodes
  initNodeGrid();
}

function draw() {
  background(240, 40, 8, 0.25); // Subtle trail background for motion decay

  // Update and render expanding ripples (Array 2)
  for (let i = ripples.length - 1; i >= 0; i--) {
    let r = ripples[i];
    noFill();
    stroke(r.hue, 80, 100, r.alpha);
    strokeWeight(r.weight);
    ellipse(r.x, r.y, r.radius * 2);

    // Dynamic state update
    r.radius += r.speed;
    r.alpha -= 0.015;

    // Remove dead array elements
    if (r.alpha <= 0) {
      ripples.splice(i, 1);
    }
  }

  // Draw inter-node connection lines (Lighting matrix topology)
  for (let i = 0; i < nodes.length; i++) {
    for (let j = i + 1; j < nodes.length; j++) {
      let d = dist(nodes[i].x, nodes[i].y, nodes[j].x, nodes[j].y);
      if (d < 140) {
        let alpha = map(d, 0, 140, 0.6, 0);
        stroke(nodes[i].hue, 70, 90, alpha);
        strokeWeight(map(d, 0, 140, 2, 0.5));
        line(nodes[i].x, nodes[i].y, nodes[j].x, nodes[j].y);
      }
    }
  }

  // Update and render nodes (Array 1)
  for (let i = 0; i < nodes.length; i++) {
    let n = nodes[i];

    // Physics update: slight movement drifting
    n.x += n.vx;
    n.y += n.vy;

    // Boundary bounces
    if (n.x < 0 || n.x > width) n.vx *= -1;
    if (n.y < 0 || n.y > height) n.vy *= -1;

    // User interaction response: mouse proximity effect
    let mouseD = dist(mouseX, mouseY, n.x, n.y);
    let currentRadius = n.baseRadius;
    
    if (mouseD < 120) {
      let boost = map(mouseD, 0, 120, 20, 0);
      currentRadius += boost;

      // Draw active targeting/interaction link to cursor
      stroke(n.hue, 100, 100, 0.4);
      strokeWeight(1);
      line(n.x, n.y, mouseX, mouseY);
    }

    // Node Render (Glow effect layers)
    noStroke();
    fill(n.hue, 80, 100, 0.2);
    ellipse(n.x, n.y, currentRadius * 2.2);

    fill(n.hue, 90, 100, 0.9);
    ellipse(n.x, n.y, currentRadius);

    fill(0, 0, 100, 0.9);
    ellipse(n.x, n.y, currentRadius * 0.3);
  }
}

// User Input: Mouse Click triggers new node addition & visual ripple
function mousePressed() {
  let selectedColor = random(nodePalette);
  let newHue = hue(color(selectedColor[0], selectedColor[1], selectedColor[2]));

  // Add new element to Array 1 (Nodes)
  nodes.push({
    x: mouseX,
    y: mouseY,
    vx: random(-0.8, 0.8),
    vy: random(-0.8, 0.8),
    baseRadius: random(8, 16),
    hue: random(180, 320)
  });

  // Add new element to Array 2 (Ripples)
  ripples.push({
    x: mouseX,
    y: mouseY,
    radius: 5,
    speed: random(3, 6),
    alpha: 0.8,
    weight: 2,
    hue: random(180, 320)
  });
}

// User Input: Keyboard Controls
function keyPressed() {
  if (key === 'c' || key === 'C') {
    nodes = [];
    ripples = [];
  } else if (key === 'r' || key === 'R') {
    initNodeGrid();
  }
}

// Helper to seed initial node positions across the canvas
function initNodeGrid() {
  nodes = [];
  let cols = 6;
  let rows = 4;
  let spacingX = width / (cols + 1);
  let spacingY = height / (rows + 1);

  for (let i = 1; i <= cols; i++) {
    for (let j = 1; j <= rows; j++) {
      nodes.push({
        x: i * spacingX + random(-20, 20),
        y: j * spacingY + random(-20, 20),
        vx: random(-0.5, 0.5),
        vy: random(-0.5, 0.5),
        baseRadius: random(10, 14),
        hue: (i * 30 + j * 20) % 360
      });
    }
  }
}